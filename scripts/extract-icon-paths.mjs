/**
 * Extracts the raw SVG geometry of the icon vocabulary into `data/icon-paths.ts`.
 *
 * The engine needs `d` strings — to animate stroke-dashoffset and to feed
 * Rough.js — and `lucide-react` only exports React components. Rather than
 * reach into its internals at runtime, we snapshot the paths at build time.
 *
 * Run after changing `lib/storyboard/icons.ts`:
 *   node scripts/extract-icon-paths.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const vocabulary = readFileSync("lib/storyboard/icons.ts", "utf8");
const ids = [...vocabulary.matchAll(/^\s+"([A-Z][A-Za-z0-9]*)",?$/gm)].map((m) => m[1]);

/**
 * Maps every exported icon name to the module that defines it, straight from
 * lucide's own index. Guessing file names from PascalCase breaks on digits
 * (Volume2 -> volume-2) and on aliases (History -> rotate-ccw-clock).
 */
function buildNameMap() {
  const index = readFileSync(
    "node_modules/lucide-react/dist/esm/lucide-react.mjs",
    "utf8",
  );
  const map = new Map();
  for (const line of index.split("\n")) {
    const from = line.match(/from '\.\/(icons\/[\w-]+\.mjs)'/);
    if (!from) continue;
    for (const [, name] of line.matchAll(/default as (\w+)/g)) {
      map.set(name, `node_modules/lucide-react/dist/esm/${from[1]}`);
    }
  }
  return map;
}

/** Alias modules re-export the component but not its data — follow the chain. */
async function loadIconData(file, depth = 0) {
  if (depth > 4) return null;
  const mod = await import(pathToFileURL(file).href);
  if (mod.__iconData) return mod.__iconData;

  const source = readFileSync(file, "utf8");
  const target = source.match(/from '\.\/([\w-]+\.mjs)'/);
  if (!target) return null;
  return loadIconData(file.replace(/[\w-]+\.mjs$/, target[1]), depth + 1);
}

/** Lucide nodes are SVG primitives; the engine only speaks paths. */
function toPath([tag, attrs]) {
  switch (tag) {
    case "path":
      return attrs.d;
    case "line":
      return `M${attrs.x1} ${attrs.y1}L${attrs.x2} ${attrs.y2}`;
    case "circle": {
      const { cx, cy, r } = attrs;
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0`;
    }
    case "ellipse": {
      const { cx, cy, rx, ry } = attrs;
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0`;
    }
    case "rect": {
      const x = +attrs.x, y = +attrs.y, w = +attrs.width, h = +attrs.height;
      const r = +(attrs.rx ?? 0);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return (
        `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}` +
        `v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}` +
        `h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}` +
        `v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`
      );
    }
    case "polyline":
    case "polygon": {
      const pts = attrs.points.trim().split(/[\s,]+/);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? `${d}z` : d;
    }
    default:
      return null;
  }
}

const nameMap = buildNameMap();
const entries = [];
const missing = [];

for (const id of ids) {
  const file = nameMap.get(id);
  const data = file ? await loadIconData(file) : null;
  const paths = data ? data.node.map(toPath).filter(Boolean) : [];
  if (paths.length === 0) {
    missing.push(id);
    continue;
  }
  entries.push([id, paths, data.size ?? 24]);
}

if (missing.length) {
  console.error(`No se pudo extraer: ${missing.join(", ")}`);
  process.exit(1);
}

const body = entries
  .map(([id, paths]) => `  ${id}: [${paths.map((p) => JSON.stringify(p)).join(", ")}],`)
  .join("\n");

writeFileSync(
  "data/icon-paths.ts",
  `/**
 * SVG geometry for the icon vocabulary, on a ${entries[0][2]}x${entries[0][2]} grid.
 *
 * GENERATED by \`scripts/extract-icon-paths.mjs\` — do not edit by hand.
 * The engine strokes these paths so the hand can draw them, and passes them
 * through Rough.js for the hand-drawn wobble.
 */

export const ICON_VIEWBOX = ${entries[0][2]};

export const ICON_PATHS: Record<string, string[]> = {
${body}
};
`,
);

console.log(`${entries.length} iconos extraídos a data/icon-paths.ts`);
